"""Derive a new calibration library whose points follow an equal-|Γ| or
Smith-uniform plan, using only measured truth from an existing library.

This is deliberately NOT a new measurement: the source library must already
be calibrated.  The target Γ set is generated by :mod:`pointplan`
(``gamma_rings_targets`` / ``smith_targets``); for every target Γ the nearest
*measured* point in the source library is selected (in the complex Γ plane,
at the chosen frequency) and its **original position and S-matrix are copied
verbatim** into the new library.  Every point in the result is therefore a
real measured point — no interpolation, no synthesis, no re-test.

The new library carries lineage metadata back to the parent, exactly like
:mod:`library_ops`, so the source stays immutable and the operation is
auditable.
"""
from __future__ import annotations

import numpy as np

from .database import CalibrationDatabase
from .models import Measurement, TunerConfig
from .metadata import normalise_metadata
from .pointplan import (
    gamma_rings_targets, smith_targets, density_count, coverage_report,
)
from .rf import RFNetworkEngine as RF

__all__ = ['derive_by_gamma_plan', 'plan_target_gamma']


def plan_target_gamma(plan, *, count, r_min=0.0, r_max=0.95,
                      method='sunflower', enhanced_center=False,
                      enhanced_50ohm=False):
    """Generate the target Γ array for one of the two supported plans."""
    key = str(plan).strip().lower()
    if key == 'smith':
        return smith_targets(int(count), r_min, r_max, method=method)
    if key == 'gamma_rings':
        return gamma_rings_targets(
            int(count), r_min, r_max,
            enhanced_center=bool(enhanced_center),
            enhanced_50ohm=bool(enhanced_50ohm))
    raise ValueError(f'unknown plan {plan!r}; expected gamma_rings or smith')


def _measured_gammas(data, frequency_hz, z0):
    """Return (valid_indices, complex Γ at frequency_hz) from a loaded library."""
    valid = np.flatnonzero(np.asarray(data['valid'], bool))
    if valid.size == 0:
        raise ValueError('source library has no valid measured points')
    s = np.asarray(data['s'], complex)
    freqs = np.asarray(data['frequencies'], float)
    if frequency_hz is None:
        frequency_hz = float(freqs[len(freqs) // 2])
    else:
        frequency_hz = float(frequency_hz)
        if not (freqs[0] <= frequency_hz <= freqs[-1]):
            raise ValueError(
                f'target frequency {frequency_hz / 1e9:.6f} GHz is outside the '
                f'library grid {freqs[0] / 1e9:.6f}–{freqs[-1] / 1e9:.6f} GHz')
    # Γ of each point over all frequencies, then pick the requested frequency.
    gamma_all = RF.dut_gamma(s[valid])  # (n_valid, n_freq)
    idx = int(np.argmin(np.abs(freqs - frequency_hz)))
    gammas = gamma_all[:, idx].astype(complex)
    return valid, gammas, float(freqs[idx])


def derive_by_gamma_plan(src_db, new_path, *, plan='gamma_rings', density='medium',
                         r_min=0.0, r_max=0.95, method='sunflower',
                         enhanced_center=False, enhanced_50ohm=False,
                         frequency_hz=None, dedupe=False):
    """Create a new library of measured truth points following a Γ plan.

    For every target Γ, the nearest measured point (by |Γ_target − Γ_measured|)
    is chosen and copied verbatim (position, actual, S, all point records).
    A measured point may serve several neighbouring targets by default; set
    ``dedupe=True`` to keep only the first occurrence of each source point.

    Returns a summary dict with the new path, point count, lineage and the
    coverage report of the resulting Γ distribution against the targets.
    """
    data = src_db.load()
    meta = normalise_metadata(data['metadata'])
    z0 = float(meta.get('z0', 50.0) or 50.0)
    count = density_count(density)
    targets = plan_target_gamma(
        plan, count=count, r_min=r_min, r_max=r_max, method=method,
        enhanced_center=enhanced_center, enhanced_50ohm=enhanced_50ohm)

    valid, gammas, used_freq = _measured_gammas(data, frequency_hz, z0)

    # Nearest measured point for each target in the complex Γ plane.
    # (n_target, n_valid) distance matrix; libraries are at most a few thousand
    # points so this is cheap and needs no extra dependency.
    diff = targets[:, None] - gammas[None, :]
    dist = np.abs(diff)
    nearest = np.argmin(dist, axis=1)
    dist_min = dist[np.arange(len(targets)), nearest]

    chosen = [int(valid[i]) for i in nearest]
    if dedupe:
        seen = set()
        unique = []
        for index in chosen:
            if index not in seen:
                seen.add(index)
                unique.append(index)
        chosen = unique

    # Copy the chosen measured points verbatim into a brand-new library.
    src_positions = np.asarray(data['positions'], float)
    src_actual = np.asarray(data['actual'], float)
    src_s = np.asarray(data['s'], complex)
    positions = src_positions[chosen].copy()
    actual = src_actual[chosen].copy()

    target = CalibrationDatabase(str(new_path))
    exclude = {'version_id', 'created', 'schema_version', 'config',
               'simulated', 'cal_id'}
    new_meta = {k: v for k, v in meta.items() if k not in exclude}
    new_meta.update(
        parent_version=meta.get('version_id'),
        version_reason=f'derive by {plan} plan',
        operation='derive_gamma_plan',
        point_plan=plan,
        plan_density=str(density),
        plan_r_min=float(r_min),
        plan_r_max=float(r_max),
        plan_frequency_hz=used_freq,
    )
    target.create(
        TunerConfig(**meta['config']),
        np.asarray(data['frequencies'], float), positions, new_meta)
    for k, src_idx in enumerate(chosen):
        meas = Measurement(np.asarray(data['frequencies'], float),
                           src_s[src_idx], bool(meta.get('simulated', False)))
        target.write_point(k, actual[k], meas)

    result_gammas = gammas[nearest]
    cov = coverage_report(result_gammas, targets)
    return {
        'path': str(target.path),
        'cal_id': str(target.read_metadata().get('cal_id', '')),
        'points': len(chosen),
        'plan': plan,
        'density': str(density),
        'frequency_hz': used_freq,
        'parent_version': meta.get('version_id'),
        'deduped': bool(dedupe),
        'max_nearest_distance': float(np.max(dist_min)) if dist_min.size else 0.0,
        'mean_nearest_distance': float(np.mean(dist_min)) if dist_min.size else 0.0,
        'coverage': cov,
    }
